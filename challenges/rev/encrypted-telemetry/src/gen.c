/* Build-time generator: seal the flag under the key that killing all
 * RS_DRONES drones produces, and emit it as a C header for the game.
 *
 *   gen 'flag{...}' > build/ct.h
 */
#include <stdio.h>
#include <string.h>
#include "shard.h"

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: %s FLAG > ct.h\n", argv[0]);
        return 2;
    }
    if (sodium_init() < 0)
        return 1;

    uint8_t acc[16] = {0}, sh[16], key[32];
    uint8_t nonce[crypto_aead_chacha20poly1305_ietf_NPUBBYTES];
    for (uint32_t id = 0; id < RS_DRONES; id++) {
        rs_shard(id, sh);
        for (int i = 0; i < 16; i++)
            acc[i] ^= sh[i];
    }
    rs_key(acc, key);
    rs_nonce(nonce);

    const unsigned char *m = (const unsigned char *)argv[1];
    unsigned long long mlen = strlen(argv[1]), clen;
    unsigned char ct[512];
    if (mlen + crypto_aead_chacha20poly1305_ietf_ABYTES > sizeof ct)
        return 1;
    crypto_aead_chacha20poly1305_ietf_encrypt(ct, &clen, m, mlen, NULL, 0, NULL, nonce, key);

    printf("/* generated by gen.c -- do not edit */\n");
    printf("static const unsigned char rs_ct[%llu] = {", clen);
    for (unsigned long long i = 0; i < clen; i++)
        printf("%s0x%02x,", i % 12 ? " " : "\n    ", ct[i]);
    printf("\n};\n");
    return 0;
}
